export const people = pgTable(
  'people',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    displayName: text('display_name').notNull(),
    /** E.164, normalized before it reaches this column. Routing key, not a credential. */
    phoneE164: text('phone_e164').notNull(),
    role: personRole('role').notNull(),
    /** Non-null means explicitly enrolled in the demo; null means known but not enrolled. */
    enrolledAt: timestamp('enrolled_at', { withTimezone: true }),
    /** Opens this recipient's 24-hour WhatsApp service window. Per person, never shared. */
    lastWhatsappInboundAt: timestamp('last_whatsapp_inbound_at', { withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    // One person per number: the routing lookup must never find two candidates.
    unique('people_phone_e164_key').on(t.phoneE164),
    // Defense in depth behind `normalizePhone`: a national number cannot land here
    // even if some future caller forgets to normalize.
    check('people_phone_e164_is_e164', sql`${t.phoneE164} ~ '^\\+[1-9][0-9]{6,14}$'`),
    check('people_display_name_not_blank', sql`length(btrim(${t.displayName})) > 0`),
  ],
);

