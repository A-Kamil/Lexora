export const deadlines = pgTable(
  'deadlines',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    caseId: uuid('case_id').notNull(),
    title: text('title').notNull(),
    dueAt: timestamp('due_at', { withTimezone: true }).notNull(),
    /** The zone the deadline was stated in, which is not necessarily the case's. */
    timezone: text('timezone').notNull(),
    sourceDocumentId: uuid('source_document_id'),
    sourceMessageId: uuid('source_message_id'),
    /**
     * Defaults to `unverified`, and nothing promotes it automatically. A date a model
     * read out of a document is a lead for the lawyer, not a court date.
     */
    verificationStatus: verificationStatus('verification_status').notNull().default('unverified'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    foreignKey({
      name: 'deadlines_case_id_fkey',
      columns: [t.caseId],
      foreignColumns: [cases.id],
    }).onDelete('restrict'),
    // Ownership for both optional sources. `restrict` rather than `set null`: a
    // composite `set null` would try to null the NOT NULL `case_id`, and a legal
    // deadline should not outlive the evidence it came from silently anyway.
    foreignKey({
      name: 'deadlines_source_document_case_fkey',
      columns: [t.sourceDocumentId, t.caseId],
      foreignColumns: [documents.id, documents.caseId],
    }).onDelete('restrict'),
    foreignKey({
      name: 'deadlines_source_message_case_fkey',
      columns: [t.sourceMessageId, t.caseId],
      foreignColumns: [messages.id, messages.caseId],
    }).onDelete('restrict'),
    check('deadlines_title_not_blank', sql`length(btrim(${t.title})) > 0`),
    check('deadlines_timezone_not_blank', sql`length(btrim(${t.timezone})) > 0`),
    // `getDeadlines(caseId)` returns a case's deadlines in due order.
    index('deadlines_case_due_at_idx').on(t.caseId, t.dueAt, t.id),
  ],
);

