/**
 * The nine domain tables.
 *
 * Three conventions hold throughout:
 *
 * 1. **Identifiers** are UUIDs generated by PostgreSQL (`gen_random_uuid()`, built in
 *    since PG 13), so a writer never has to invent an id to build a graph.
 * 2. **Instants** are `timestamptz`. A case additionally stores its IANA zone, because
 *    an instant alone cannot render a hearing time the way a court states it.
 * 3. **Deletes do not cascade through case history.** Relationships default to
 *    `restrict`; `set null` appears only where the column is already nullable and
 *    losing the pointer is harmless. Nothing in this schema lets deleting a person
 *    quietly erase the record of a case.
 *
 * ## Cross-case ownership
 *
 * Every table that carries both a `case_id` and a pointer to a parent row enforces
 * agreement between the two with a **composite foreign key**, not an application check.
 * That requires a `unique (id, case_id)` on each parent — redundant with the primary
 * key as storage, but it is what makes PostgreSQL itself reject
 * `message.case_id <> conversation.case_id`. Those unique constraints exist for that
 * single purpose and are marked below.
 *
 * Because PostgreSQL composite foreign keys default to `MATCH SIMPLE`, a row with a
 * NULL in the pointer column satisfies the constraint regardless of its `case_id`.
 * That is exactly the wanted behavior for optional parents such as a deadline's source.
 *
 * ## Blank strings in uniqueness columns
 *
 * Every text column that takes part in a uniqueness or idempotency decision carries a
 * `_not_blank` check. `''` is not a missing value to PostgreSQL: it satisfies NOT NULL
 * and it occupies the unique slot. An empty `trigger_key` is the sharp case — two
 * unrelated analyses would collide on it, and the second would be handed the first's
 * result as though it were its own. A blank value must be rejected, not deduplicated.
 */

