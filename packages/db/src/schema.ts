export const documents = pgTable(
  'documents',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    caseId: uuid('case_id').notNull(),
    messageId: uuid('message_id').notNull(),
    /** Position of the attachment within its message, 0-based. */
    mediaIndex: integer('media_index').notNull(),
    /**
     * Private object key, deterministically `{caseId}/{documentId}/original`, so a
     * retried upload addresses the same object instead of orphaning the first one.
     * A key, never a URL: nothing in this schema stores a public or signed link.
     */
    storageKey: text('storage_key').notNull(),
    mimeType: text('mime_type').notNull(),
    /** Null while `pending`: the bytes have not been fetched yet. */
    byteSize: bigint('byte_size', { mode: 'number' }),
    sha256: text('sha256'),
    status: documentStatus('status').notNull().default('pending'),
    extractedText: text('extracted_text'),
    /** Validated extraction metadata: document type, summary, unverified date mentions. */
    metadata: jsonb('metadata').$type<DocumentMetadata>().notNull().default({}),
    errorCode: text('error_code'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    foreignKey({
      name: 'documents_case_id_fkey',
      columns: [t.caseId],
      foreignColumns: [cases.id],
    }).onDelete('restrict'),
    // Ownership: a document cannot belong to a case other than its message's.
    foreignKey({
      name: 'documents_message_case_fkey',
      columns: [t.messageId, t.caseId],
      foreignColumns: [messages.id, messages.caseId],
    }).onDelete('restrict'),
    // One row per attachment slot: a replayed intake cannot create a second placeholder.
    unique('documents_message_id_media_index_key').on(t.messageId, t.mediaIndex),
    // One row per object key, so a restart-time reconcile cannot find two owners.
    unique('documents_storage_key_key').on(t.storageKey),
    check('documents_media_index_non_negative', sql`${t.mediaIndex} >= 0`),
    // Blank would take the unique slot while addressing no object at all.
    check('documents_storage_key_not_blank', sql`length(btrim(${t.storageKey})) > 0`),
    check('documents_mime_type_not_blank', sql`length(btrim(${t.mimeType})) > 0`),
    // Having stored the bytes means knowing their size and digest.
    check(
      'documents_stored_has_bytes',
      sql`${t.status} NOT IN ('stored', 'extracting', 'ready') OR (${t.byteSize} IS NOT NULL AND ${t.sha256} IS NOT NULL)`,
    ),
    // `ready` is the claim that text was extracted. Empty text is a valid extraction
    // result; absent text is not.
    check(
      'documents_ready_has_text',
      sql`${t.status} <> 'ready' OR ${t.extractedText} IS NOT NULL`,
    ),
    // A terminal failure must say why, and `error_code IS NOT NULL` alone does not get
    // that: `''` satisfies it while carrying no diagnosis. A short machine-readable code
    // such as `unsupported_media_type` or `ocr_timeout` is what belongs here — enough to
    // route the failure, with no provider payload, no document content and no URL.
    check(
      'documents_terminal_has_reason',
      sql`${t.status} NOT IN ('rejected', 'failed') OR length(btrim(coalesce(${t.errorCode}, ''))) > 0`,
    ),
    check(
      'documents_error_code_not_blank',
      sql`${t.errorCode} IS NULL OR length(btrim(${t.errorCode})) > 0`,
    ),
    check('documents_byte_size_non_negative', sql`${t.byteSize} IS NULL OR ${t.byteSize} >= 0`),
    // `getCaseDocuments` reads a case's documents and `CaseContext` filters to `ready`.
    index('documents_case_id_status_idx').on(t.caseId, t.status),
    // Composite-FK target for a deadline's source document.
    unique('documents_id_case_id_key').on(t.id, t.caseId),
  ],
);

