export const escalations = pgTable(
  'escalations',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    caseId: uuid('case_id').notNull(),
    analysisId: uuid('analysis_id').notNull(),
    /** Null when the case has no assigned lawyer, which is a visible failure. */
    lawyerId: uuid('lawyer_id'),
    outboundMessageId: uuid('outbound_message_id'),
    status: escalationStatus('status').notNull().default('pending'),
    reason: text('reason').notNull(),
    providerMessageId: text('provider_message_id'),
    errorCode: text('error_code'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    foreignKey({
      name: 'escalations_case_id_fkey',
      columns: [t.caseId],
      foreignColumns: [cases.id],
    }).onDelete('restrict'),
    // Ownership: the analysis escalated must belong to the case recorded here.
    foreignKey({
      name: 'escalations_analysis_case_fkey',
      columns: [t.analysisId, t.caseId],
      foreignColumns: [analyses.id, analyses.caseId],
    }).onDelete('restrict'),
    // Ownership: the alerted lawyer must be a member of this case.
    foreignKey({
      name: 'escalations_lawyer_case_member_fkey',
      columns: [t.caseId, t.lawyerId],
      foreignColumns: [caseMembers.caseId, caseMembers.personId],
    }).onDelete('restrict'),
    // Ownership: the outbound alert message must belong to this case.
    foreignKey({
      name: 'escalations_outbound_message_case_fkey',
      columns: [t.outboundMessageId, t.caseId],
      foreignColumns: [messages.id, messages.caseId],
    }).onDelete('restrict'),
    // One analysis escalates at most once. This is the whole duplicate-alert defense.
    unique('escalations_analysis_id_key').on(t.analysisId),
    check('escalations_reason_not_blank', sql`length(btrim(${t.reason})) > 0`),
    // `blocked_no_lawyer` is only coherent when there is in fact no lawyer.
    check(
      'escalations_blocked_no_lawyer_has_no_lawyer',
      sql`${t.status} <> 'blocked_no_lawyer' OR ${t.lawyerId} IS NULL`,
    ),
    index('escalations_case_created_at_idx').on(t.caseId, t.createdAt.desc()),
  ],
);
