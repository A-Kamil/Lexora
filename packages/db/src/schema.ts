export const analyses = pgTable(
  'analyses',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    caseId: uuid('case_id').notNull(),
    conversationId: uuid('conversation_id').notNull(),
    /**
     * Identifies the input event and revision this analysis answers, e.g.
     * `message:{id}:v1` or `document:{id}:ready:v1`. Unique, which is what makes a
     * restarted job reuse the existing result instead of paying for a second one.
     */
    triggerKey: text('trigger_key').notNull(),
    /** A validated `CaseAnalysis`. JSONB because the public contract is versioned. */
    result: jsonb('result').$type<CaseAnalysis>().notNull(),
    status: analysisStatus('status').notNull(),
    /**
     * On a `fallback` this is the model that was *attempted*, not one that answered.
     * Provenance has to record which model the failure is attributable to, so this
     * column is never blank even when no response came back.
     */
    model: text('model').notNull(),
    promptVersion: text('prompt_version').notNull(),
    schemaVersion: integer('schema_version').notNull(),
    /** Provenance snapshot: exactly what the model was shown. */
    contextMessageIds: uuid('context_message_ids')
      .array()
      .notNull()
      .default(sql`'{}'::uuid[]`),
    contextDocumentIds: uuid('context_document_ids')
      .array()
      .notNull()
      .default(sql`'{}'::uuid[]`),
    // Append-only: an analysis records one assessment at one instant and is never edited.
    createdAt: createdAt(),
  },
  (t) => [
    foreignKey({
      name: 'analyses_case_id_fkey',
      columns: [t.caseId],
      foreignColumns: [cases.id],
    }).onDelete('restrict'),
    // Ownership: the conversation analysed must belong to the case recorded here.
    foreignKey({
      name: 'analyses_conversation_case_fkey',
      columns: [t.conversationId, t.caseId],
      foreignColumns: [conversations.id, conversations.caseId],
    }).onDelete('restrict'),
    unique('analyses_trigger_key_key').on(t.triggerKey),
    // The sharp case of the blank-string rule above: without this, two unrelated
    // analyses saved with an empty trigger key would collide, and `saveAnalysis` would
    // hand the second one the first's result with `existing: true`.
    check('analyses_trigger_key_not_blank', sql`length(btrim(${t.triggerKey})) > 0`),
    check('analyses_schema_version_positive', sql`${t.schemaVersion} > 0`),
    check('analyses_model_not_blank', sql`length(btrim(${t.model})) > 0`),
    check('analyses_prompt_version_not_blank', sql`length(btrim(${t.promptVersion})) > 0`),
    // `CaseContext.latestAnalysis` reads the newest analysis for a case.
    index('analyses_case_created_at_idx').on(t.caseId, t.createdAt.desc(), t.id.desc()),
    // Composite-FK target for `escalations`.
    unique('analyses_id_case_id_key').on(t.id, t.caseId),
  ],
);

